#!/usr/bin/env python3
"""Convert a fixed-width BDF font to a C array of printable ASCII glyphs.

usage: bdf2c.py FONT.bdf NAME > out.h

Emits:  static const uint8_t NAME[95][H][(W+7)/8];  // glyphs 0x20..0x7e, MSB = leftmost
        #define NAME_W / NAME_H
"""
import sys


def parse(path):
    w = h = None
    glyphs, cur, bitmap, in_bitmap = {}, None, [], False
    for line in open(path, encoding="latin-1"):
        parts = line.split()
        if not parts:
            continue
        key = parts[0]
        if key == "FONTBOUNDINGBOX":
            w, h = int(parts[1]), int(parts[2])
        elif key == "ENCODING":
            cur = int(parts[1])
        elif key == "BITMAP":
            in_bitmap, bitmap = True, []
        elif key == "ENDCHAR":
            if cur is not None and 0x20 <= cur <= 0x7E:
                glyphs[cur] = bitmap
            in_bitmap, cur = False, None
        elif in_bitmap:
            bitmap.append(int(key, 16))
    return w, h, glyphs


def main():
    path, name = sys.argv[1], sys.argv[2]
    w, h, glyphs = parse(path)
    bpr = (w + 7) // 8
    out = [f"/* generated by tools/bdf2c.py from {path.split('/')[-1]} */",
           f"#define {name}_W {w}", f"#define {name}_H {h}",
           f"static const uint8_t {name}[95][{h}][{bpr}] = {{"]
    for c in range(0x20, 0x7F):
        rows = glyphs.get(c, [0] * h)
        rows = (rows + [0] * h)[:h]
        cells = ", ".join(
            "{" + ", ".join(f"0x{(r >> (8 * (bpr - 1 - i))) & 0xFF:02x}" for i in range(bpr)) + "}"
            for r in rows)
        out.append(f"\t/* {chr(c)!r} */ {{{cells}}},")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
